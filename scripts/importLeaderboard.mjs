// Turns the data team's weekly leaderboard CSV into src/data/leaderboardWeek.ts.
// Usage: node scripts/importLeaderboard.mjs "<path to csv>"
// Names are stored as first name plus last initial; usernames stay only to match the signed-in user.
import { readFileSync, writeFileSync } from 'node:fs';

const path = process.argv[2];
if (!path) {
  console.error('Usage: node scripts/importLeaderboard.mjs "<path to csv>"');
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.some((v) => v !== '')) rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

const [header, ...body] = parseCsv(readFileSync(path, 'utf8'));
const col = (name) => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`Missing column: ${name}`);
  return i;
};
const [iUser, iRef, iCash, iCount, iLast, iYear, iWeek] =
  ['username', 'referrals', 'cashback', 'count', 'last_txn_period', 'year', 'week'].map(col);
// full_name is optional (newer exports drop it). Without it, reuse the name already in
// src/data/leaderboardWeek.ts for that username, else fall back to the username.
const iName = header.indexOf('full_name');
const known = new Map();
try {
  const prev = readFileSync(new URL('../src/data/leaderboardWeek.ts', import.meta.url), 'utf8');
  for (const m of prev.matchAll(/"username": "([^"]+)",\s*"name": "([^"]+)",\s*"initials": "([^"]+)"/g)) {
    known.set(m[1], { name: m[2], initials: m[3] });
  }
} catch {}
const missing = [];

function shortName(full) {
  const parts = full.trim().split(/\s+/);
  if (parts.length < 2) return parts[0];
  return `${parts[0]} ${parts[parts.length - 1][0].toUpperCase()}.`;
}
function initials(full) {
  const parts = full.trim().split(/\s+/);
  return (parts[0][0] + (parts.length > 1 ? parts[parts.length - 1][0] : '')).toUpperCase();
}

const weeks = new Set(body.map((r) => `${r[iYear]}-${r[iWeek]}`));
if (weeks.size !== 1) throw new Error(`Expected one week in the file, found: ${[...weeks].join(', ')}`);

// Highest cashback first; on a tie, whoever reached it first (earlier last transaction).
const rows = body
  .map((r) => {
    const username = r[iUser].trim().toLowerCase();
    let ident;
    if (iName !== -1 && r[iName]?.trim()) ident = { name: shortName(r[iName]), initials: initials(r[iName]) };
    else if (known.has(username)) ident = known.get(username);
    else {
      missing.push(username);
      ident = { name: username, initials: username.slice(0, 2).toUpperCase() };
    }
    return { username, ...ident, r };
  })
  .map(({ username, name, initials, r }) => ({
    username,
    name,
    initials,
    cashback: Number(r[iCash]),
    referrals: Number(r[iRef]),
    count: Number(r[iCount]),
    lastTxn: r[iLast],
  }))
  .sort((a, b) => b.cashback - a.cashback || a.lastTxn.localeCompare(b.lastTxn));

const [year, week] = [...weeks][0].split('-').map(Number);
const out = `// Generated by scripts/importLeaderboard.mjs from the data team's CSV. Do not edit by hand.
// Sorted by cashback, highest first. The leaderboard shows the Top 20 who are at or above the minimum.

export interface WeekRow {
  username: string;
  /** First name and last initial. */
  name: string;
  initials: string;
  cashback: number;
  referrals: number;
  /** Number of transactions (the volume track). */
  count: number;
  lastTxn: string;
}

export const WEEK_YEAR = ${year};
export const WEEK_NUMBER = ${week};

export const WEEK_ROWS: WeekRow[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL('../src/data/leaderboardWeek.ts', import.meta.url), out);
if (missing.length) console.warn(`No name known for: ${missing.join(', ')} (showing username)`);
console.log(`Wrote ${rows.length} rows for week ${week} of ${year}.`);
